import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as icons from 'simple-icons'

/**
 * Refresh components/share-icons.ts from simple-icons.
 *
 * Run with `npm run icons:sync`. The output is committed, so this is only
 * needed when a logo changes or a network is added to the list below — nothing
 * at build or request time reads the package, and it stays a devDependency for
 * that reason.
 *
 * The package is the reason to do this at all: these are the marks as their
 * owners publish them, kept current by people who watch for rebrands, which is
 * not a thing to redraw by hand. What we do not want is the shipping cost — its
 * entry point is a single five-megabyte module holding all 3,450 icons, and
 * leaning on the bundler to shake 3,417 of them out of every build is a slow
 * way to arrive at the file this script writes in a second.
 *
 * Brand colours come across too. A logo has one, it is part of the mark, and
 * hard-coding hexes here would mean maintaining a second copy of something the
 * package already states.
 */

const SLUGS = [
  'whatsapp',
  'telegram',
  'x',
  'facebook',
  'reddit',
  'bluesky',
  'threads',
  'mastodon',
  'tumblr',
  'pinterest',
  'line',
  'viber',
  'threema',
  'vk',
  'odnoklassniki',
  'maildotru',
  'sinaweibo',
  'qq',
  'qzone',
  'douban',
  'baidu',
  'naver',
  'hatenabookmark',
  'ycombinator',
  'livejournal',
  'blogger',
  'flipboard',
  'wykop',
  'draugiemdotlv',
  'diaspora',
  'xing',
]

const here = dirname(fileURLToPath(import.meta.url))
const to = join(here, '..', 'components', 'share-icons.ts')

const marks = SLUGS.map((slug) => {
  const mark = Object.values(icons).find((icon) => icon.slug === slug)

  if (!mark) throw new Error(`simple-icons has no icon with slug "${slug}"`)

  return { slug, title: mark.title, hex: `#${mark.hex}`, path: mark.path }
})

const body = marks
  .map(
    ({ slug, title, hex, path }) =>
      `  ${slug}: {\n    title: ${JSON.stringify(title)},\n    hex: ${JSON.stringify(hex)},\n    path: ${JSON.stringify(path)},\n  },`,
  )
  .join('\n')

writeFileSync(
  to,
  `// Generated by scripts/sync-share-icons.mjs — do not edit by hand.
// Logos and brand colours as published by their owners, via simple-icons.

export type Mark = { title: string; hex: string; path: string }

export const MARKS = {
${body}
} satisfies Record<string, Mark>
`,
)

console.log(`${marks.length} marks → components/share-icons.ts`)
